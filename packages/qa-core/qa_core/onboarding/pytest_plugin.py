"""A tiny pytest plugin the platform writes into an imported workspace.

It has to run inside the *project's* interpreter, which cannot import the platform's packages, so the
source lives here as a string and is materialised into the workspace before a run. It records one JSON
line per test attempt, which makes rerun accounting exact and immune to output interleaving — the
reference project's own logging splits pytest's progress lines, so text parsing alone is not reliable.
"""

from __future__ import annotations

PLUGIN_MODULE_NAME = "qa_platform_report_plugin"

PLUGIN_SOURCE = '''"""Generated by the AI QA Platform. Records one JSON line per test attempt."""

from __future__ import annotations

import json
import os

PLUGIN_NAME = "qa-platform-report"
ENV_PATH = "QA_PLATFORM_REPORT_LOG"


class QAReportPlugin:
    def __init__(self, path):
        # With xdist every worker runs this plugin, so each one writes its own file: a shared file
        # would be truncated by the next worker and interleaved by concurrent writes.
        worker = os.environ.get("PYTEST_XDIST_WORKER", "main")
        self._handle = open(f"{path}.{worker}", "a", encoding="utf-8")

    def pytest_runtest_logreport(self, report):
        record = {
            "nodeid": report.nodeid,
            "when": report.when,
            "outcome": report.outcome,
            "duration": report.duration,
            # pytest marks expected failures with `wasxfail`; without it an xfail looks like a skip.
            "xfail": getattr(report, "wasxfail", None) is not None,
        }
        longrepr = report.longrepr
        if longrepr is not None:
            text = str(longrepr).strip()
            record["longrepr"] = text.splitlines()[-1][:2000] if text else None
            record["stack_trace"] = text[-16000:]
            crash = getattr(longrepr, "reprcrash", None)
            record["error_message"] = str(crash.message)[:3000] if crash else record["longrepr"]
        self._handle.write(json.dumps(record, ensure_ascii=False) + "\\n")
        self._handle.flush()

    def close(self):
        try:
            self._handle.close()
        except Exception:
            pass


def pytest_configure(config):
    path = os.environ.get(ENV_PATH)
    if not path:
        return
    # Under xdist only the workers record: the controller receives the same reports aggregated, so
    # writing there as well would double every attempt.
    parallel = bool(getattr(config.option, "numprocesses", None))
    is_worker = hasattr(config, "workerinput")
    if parallel and not is_worker:
        return
    config.pluginmanager.register(QAReportPlugin(path), PLUGIN_NAME)


def pytest_unconfigure(config):
    plugin = config.pluginmanager.get_plugin(PLUGIN_NAME)
    if plugin is not None:
        plugin.close()
        config.pluginmanager.unregister(plugin)
'''


def write_plugin(artifacts_dir) -> str:
    """Materialise the plugin into the workspace and return its importable module name."""
    path = artifacts_dir / f"{PLUGIN_MODULE_NAME}.py"
    path.write_text(PLUGIN_SOURCE, encoding="utf-8")
    return PLUGIN_MODULE_NAME
